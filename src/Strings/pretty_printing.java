package Strings;

public class pretty_printing {
    public static void main(String[] args) {
        float a = 346.243f;
        System.out.printf("Formated Number %.2f\n",a);
        System.out.printf("Math: %.2f",Math.PI);
    }
    // %c---chachter
    // %d---decimal number(base 10)
    // %f---Floating numbers
    // %s---for String
    // %t---time/date
}
